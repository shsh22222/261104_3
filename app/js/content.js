/**
 * 指を置いているあいだの流れ。入口から始まり、全身へ広がる。
 * @returns {[number, string[], string][]} [ミリ秒, 光らせる場所, 言葉]
 */
export function holdSequence(entry = 'hands') {
  const first = {
    hands: ['指先が、触れている感覚。', 'その手の内側に、何か感じますか。'],
    feet: ['足の裏が、触れている感覚。', 'その足の内側に、何か感じますか。'],
    belly: ['お腹のあたりに、注意を置きます。', 'ふくらみ、しぼむ。その内側の感じ。'],
    chest: ['胸のあたりに、そっと注意を。', 'その内側の、生きている感じ。'],
    whole: ['体全体を、内側から。', '生きている感じのするところは、どこですか。'],
  }[entry] || ['指先が、触れている感覚。', 'その手の内側に、何か感じますか。'];
  const start = entry === 'whole' ? ['whole'] : [entry];
  const spread = { hands: ['hands', 'arms'], feet: ['feet', 'legs'], belly: ['belly', 'chest'], chest: ['chest', 'belly'], whole: ['whole'] }[entry] || ['hands', 'arms'];
  return [
    [800, start, first[0]],
    [6500, start, first[1]],
    [14000, spread, 'その感じが、少しずつ広がっていく。'],
    [24000, [...new Set([...spread, 'belly', 'chest'])], '息は、体がしています。'],
    [36000, ['whole'], '体全体が、ひとつの生きている場。'],
    [50000, ['whole'], 'ただ、内側から感じている。'],
  ];
}

export function practiceMinutes(p) {
  const s = p.steps.reduce((a, b) => a + b.d, 0) + 6;
  return Math.max(1, Math.round(s / 60));
}

