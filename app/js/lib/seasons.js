export const KO_COUNT = KO.length;

/** 日付から、その日の節気と候を返す（目安）。 */
export function seasonFor(date = new Date()) {
  const key = (date.getMonth() + 1) * 100 + date.getDate();
  let hit = KO[KO.length - 1];
  for (const k of KO) {
    if (k[0] * 100 + k[1] <= key) hit = k;
    else break;
  }
  const [, , ko, koKana, gloss, sekki, sekkiKana] = hit;
  return { ko, koKana, gloss, sekki, sekkiKana };
}
